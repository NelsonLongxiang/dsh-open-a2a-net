#!/usr/bin/env node
/** Compose the package's A2A agent presets; usage: node scripts/build-agent-presets.mjs --write|--check. */
import { readFileSync, realpathSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = new URL('../', import.meta.url)
const PROMPTS = new URL('src/superagent/prompts/', ROOT)
const TEMPLATE = new URL('src/superagent/presets.patch.yml', ROOT)
const OUTPUT = new URL('cordis.patch.yml', ROOT)
const GENERATED = '# Generated by scripts/build-agent-presets.mjs; edit src/superagent/presets.patch.yml and src/superagent/prompts/, then run pnpm build:presets.\n'

/** Share the transport boundary as text only; role composition and permissions stay in the template. */
export const PRESET_PROMPT_PARTS = Object.freeze({
  router: ['router', 'team-transport'],
  member: ['member', 'team-transport'],
  observer: ['observer', 'team-transport'],
})

/** Render one role's model-facing text without deployment paths or runtime file reads. */
export function presetPrompt(role) {
  const parts = PRESET_PROMPT_PARTS[role]
  if (!Object.hasOwn(PRESET_PROMPT_PARTS, role)) throw Error(`Unknown A2A preset role: ${role}`)
  return parts.map(part => {
    const text = readFileSync(new URL(`${part}.md`, PROMPTS), 'utf8').trim()
    if (!text) throw Error(`Empty A2A prompt fragment: ${part}`)
    return text
  }).join('\n\n') + '\n'
}

/** Inline exactly one marker per role, failing on missing, duplicate or unknown markers. */
export function renderPresetPatch(template = readFileSync(TEMPLATE, 'utf8')) {
  let output = template
  for (const role of Object.keys(PRESET_PROMPT_PARTS)) {
    const marker = `                @a2a-prompt(${role})\n`
    if (output.split(marker).length !== 2) throw Error(`Expected one A2A prompt marker: ${role}`)
    const indented = presetPrompt(role).split('\n').slice(0, -1).map(line => line ? `                ${line}` : '').join('\n') + '\n'
    output = output.replace(marker, () => indented)
  }
  if (output.includes('@a2a-prompt(')) throw Error('Unknown A2A prompt marker')
  return GENERATED + output
}

// Compare real paths: a symlinked directory (macOS /var -> /private/var) would otherwise skip the CLI and exit 0.
if (process.argv[1] && realpathSync(resolve(process.argv[1])) === realpathSync(fileURLToPath(import.meta.url))) {
  const [mode, ...extra] = process.argv.slice(2)
  if (!['--write', '--check'].includes(mode) || extra.length) throw Error('usage: node scripts/build-agent-presets.mjs --write|--check')
  const rendered = renderPresetPatch()
  if (mode === '--write') {
    writeFileSync(OUTPUT, rendered)
    console.log('agent-presets: cordis.patch.yml generated from A2A-owned sources')
  } else if (readFileSync(OUTPUT, 'utf8') !== rendered) {
    console.error('agent-presets: generated patch is stale; run pnpm build:presets')
    process.exitCode = 1
  } else {
    console.log('agent-presets: generated patch matches A2A-owned sources')
  }
}
